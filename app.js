function normalizedLanguage() {
  const url = new URL(window.location.href);
  const lang = (url.searchParams.get("lang") || "en").toLowerCase();
  return ["en", "ja", "id"].includes(lang) ? lang : "en";
}

function applyLanguage(lang) {
  const strings = translations[lang];
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (strings[key] !== undefined) el.textContent = strings[key];
  });

  document.querySelectorAll("[data-lang-link]").forEach((el) => {
    el.classList.toggle("active", el.dataset.langLink === lang);
  });

  document.title =
    lang === "ja"
      ? "研究参加者募集 | 多言語音声感情研究"
      : lang === "id"
        ? "Rekrutmen Peserta | Studi Emosi Suara Multibahasa"
        : "Participant Recruitment | Multilingual Speech Emotion Study";

  const name = document.getElementById("contact-name");
  const email = document.getElementById("contact-email");
  const link = document.getElementById("contact-link");

  name.textContent = CONFIG.researcherName;
  email.textContent = CONFIG.researcherEmail;

  if (CONFIG.researcherEmail.includes("@") && !CONFIG.researcherEmail.includes("[")) {
    link.href = `mailto:${CONFIG.researcherEmail}?subject=${encodeURIComponent("Multilingual Speech Study - Participation Inquiry")}`;
  } else {
    link.href = "#";
    link.addEventListener("click", (event) => {
      event.preventDefault();
      alert(
        lang === "ja"
          ? "公開前に app.js の研究連絡先を設定してください。"
          : lang === "id"
            ? "Isi kontak penelitian di app.js sebelum mempublikasikan situs."
            : "Set the research contact in app.js before publishing the site."
      );
    });
  }
}

applyLanguage(normalizedLanguage());
